//! Rename beyond the identifiers of Kotlin code.
//!
//! [`features::rename_group`] and [`features::search`] find the identifiers that name a
//! declaration. This module decides what the cursor asks to rename ([`subject`]: a declaration,
//! a package, a type parameter, a label, or a name in a KDoc comment) and gathers everything
//! else that goes with it into a [`Plan`]: the names in KDoc links and `@param` tags, the file
//! that is named after a class, the directory of a package, and the entry points that
//! `kargo.toml` names (`main-class`, `entry-point`, `[[bin]]`). The plan becomes one
//! `WorkspaceEdit`, with document versions when the editor takes `documentChanges`.
//! `workspace/willRenameFiles` runs the same plans the other way round ([`will_rename`]).

use std::collections::{BTreeMap, HashMap};
use std::ops::Range;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use kargo_manifest::edit::ManifestEditor;

