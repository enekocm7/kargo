use crate::text;

/// What the editor allows and what the project looks like, for building the edit.
#[derive(Debug, Clone, Default)]
pub struct Env {
    /// The source roots of the project.
    pub roots: Vec<PathBuf>,
    /// The `kargo.toml` of each package.
    pub manifests: Vec<PathBuf>,
    /// The version of each open document, as the editor last sent it.
    pub versions: HashMap<PathBuf, i64>,
    /// The editor takes `documentChanges`.
    pub document_changes: bool,
    /// The editor takes `rename` resource operations in them.
    pub resource_renames: bool,
    /// Rename the file of a renamed class (`renameFiles` initialization option, on by default).
    pub rename_files: bool,
    /// Move the directory of a renamed package (`movePackageDirectories`, on by default).
    pub move_directories: bool,
}

impl Env {
    fn can_rename(&self) -> bool {
        self.document_changes && self.resource_renames
    }
}

/// What a rename request changes.
#[derive(Debug)]
pub enum Subject {
    /// Declarations that are renamed together (an `expect` and its `actual`s, overrides).
    Group(Vec<SymId>),
    /// A package, by its fully qualified name up to the renamed segment.
    Package(String),
    /// Type parameter `index` of declaration `owner`.
    TypeParam { unit: UnitId, owner: DeclId, index: usize },
    /// The label declared at token `tok` (`loop@`).
    Label { unit: UnitId, tok: usize },
}

/// The subject under the cursor, with the name's range and text in that file.
#[derive(Debug)]
pub struct Selection {
    pub subject: Subject,
    pub span: Range<usize>,
    pub placeholder: String,
}

/// What is to be renamed at `offset` of `unit`, or why nothing can be.
pub fn subject(an: &Analyzer, unit: UnitId, offset: usize) -> Result<Selection, String> {
    let u = an.unit(unit);
    let lx = &u.file.lexed;
    if let Some(tok) = lx.ident_at(offset) {
        let span = lx.tokens[tok].span();
        let placeholder = lx.text(&u.text, tok).to_owned();
        let subject = match lx.tokens[tok].kind {
            Tok::Label | Tok::LabelRef => label_subject(an, unit, tok)?,
            _ => ident_subject(an, unit, tok)?,
        };
        return Ok(Selection { subject, span, placeholder });
    }
    if lx.in_comment(offset) {
        return doc_subject(an, unit, offset);
    }
    Err("there is nothing to rename here".into())
}

fn ident_subject(an: &Analyzer, unit: UnitId, tok: usize) -> Result<Subject, String> {
    if let Some((owner, index)) = type_param_at(an, unit, tok) {
        return Ok(Subject::TypeParam { unit, owner, index });
    }
    let targets = features::targets_at(an, unit, tok);
    match targets.first() {
        Some(Target::Sym(m)) if an.decl(m.sym).generated => {
            let name = &an.decl(m.sym).name;
            Err(format!("`{name}` is generated by the compiler, so it can't be renamed"))
        }
        Some(Target::Sym(m)) if !m.sym.lib && !an.unit(m.sym.unit_id()).is_java() => Ok(Subject::Group(features::rename_group(an, m.sym))),
        Some(Target::Sym(m)) if !m.sym.lib => {
            let name = &an.decl(m.sym).name;
            Err(format!("`{name}` is declared in a Java file, which this server doesn't edit, so it can't be renamed"))
        }
        Some(Target::Sym(m)) => {
            let name = &an.decl(m.sym).name;
            let origin = match &an.unit(m.sym.unit_id()).origin {
                super::index::Origin::Library { name, .. } => name.clone(),
                _ => "a library".into(),
            };
            Err(format!("`{name}` is declared in {origin}, not in this project, so it can't be renamed"))
        }
        Some(Target::It { .. }) => Err("`it` is an implicit parameter; name the lambda's parameter to rename it".into()),
        Some(Target::Package(fq)) => {
            if project_has_package(an, fq) {
                Ok(Subject::Package(fq.clone()))
            } else {
                Err(format!("the package `{fq}` is not declared in this project, so it can't be renamed"))
            }
        }
        None => Err("there is no declaration to rename here".into()),
    }
}

/// Whether a file of the project is in package `fq` or below it.
fn project_has_package(an: &Analyzer, fq: &str) -> bool {
    an.proj.units.iter().any(|u| in_package(&u.file.package, fq))
}

/// Whether `package` is `fq` or inside it.
fn in_package(package: &str, fq: &str) -> bool {
    package == fq || package.strip_prefix(fq).is_some_and(|rest| rest.starts_with('.'))
}

// ----- type parameters -----

/// The declaration and index of the type parameter that the identifier `tok` declares or names.
fn type_param_at(an: &Analyzer, unit: UnitId, tok: usize) -> Option<(DeclId, usize)> {
    let u = an.unit(unit);
    let (file, lx) = (&u.file, &u.file.lexed);
    let t = lx.tokens[tok];
    if t.kind != Tok::Ident {
        return None;
    }
    for (di, d) in file.decls.iter().enumerate() {
        if let Some(i) = d.type_params.iter().position(|p| p.span == t.span()) {
            return Some((di, i));
        }
    }
    if tok > 0 && matches!(lx.kind(tok - 1), Some(Tok::Dot | Tok::SafeDot | Tok::ColonColon)) {
        return None;
    }
    if !file.decls_named_at(&t.span()).is_empty() {
        return None;
    }
    let name = lx.text(&u.text, tok);
    let mut best: Option<(DeclId, usize)> = None;
    for (di, d) in file.decls.iter().enumerate() {
        if !d.span.contains(&t.start) {
            continue;
        }
        if let Some(i) = d.type_params.iter().position(|p| strip_ticks(&p.name) == name)
            && best.is_none_or(|(b, _)| d.span.len() < file.decls[b].span.len())
        {
            best = Some((di, i));
        }
    }
    best
}

/// The identifier tokens that name type parameter `index` of `owner`, its declaration among them.
fn type_param_tokens(an: &Analyzer, unit: UnitId, owner: DeclId, index: usize) -> Vec<Range<usize>> {
    let u = an.unit(unit);
    let (file, lx) = (&u.file, &u.file.lexed);
    let d = &file.decls[owner];
    let param = &d.type_params[index];
    let name = strip_ticks(&param.name);
    // A declaration inside the owner that declares the same name hides it.
    let hidden: Vec<&Range<usize>> = file
        .decls
        .iter()
        .enumerate()
        .filter(|(di, o)| {
            *di != owner
                && o.type_params.iter().any(|p| strip_ticks(&p.name) == name)
                && d.span.start <= o.span.start
                && o.span.end <= d.span.end
        })
        .map(|(_, o)| &o.span)
        .collect();
    let mut out = vec![param.span.clone()];
    for &i in u.ident_tokens(name) {
        let t = lx.tokens[i];
        if t.start < d.span.start || t.end > d.span.end || t.span() == param.span {
            continue;
        }
        if i > 0 && matches!(lx.kind(i - 1), Some(Tok::Dot | Tok::SafeDot | Tok::ColonColon)) {
            continue;
        }
        if !file.decls_named_at(&t.span()).is_empty() || hidden.iter().any(|h| h.contains(&t.start)) {
            continue;
        }
        // A named argument `T = ...` or a label is not the type.
        if lx.kind(i + 1) == Some(Tok::Eq) && i > 0 && matches!(lx.kind(i - 1), Some(Tok::LParen | Tok::Comma)) {
            continue;
        }
        out.push(t.span());
    }
    out
}

pub(super) fn strip_ticks(name: &str) -> &str {
    name.strip_prefix('`').and_then(|n| n.strip_suffix('`')).unwrap_or(name)
}

// ----- labels -----

fn label_subject(an: &Analyzer, unit: UnitId, tok: usize) -> Result<Subject, String> {
    let u = an.unit(unit);
    let lx = &u.file.lexed;
    if lx.tokens[tok].kind == Tok::Label {
        return Ok(Subject::Label { unit, tok });
    }
    let name = lx.text(&u.text, tok);
    // The nearest label of that name whose labeled code holds the reference.
    let declared =
        (0..tok).rev().find(|&i| lx.kind(i) == Some(Tok::Label) && lx.text(&u.text, i) == name && label_region(lx, i).contains(&tok));
    if let Some(tok) = declared {
        return Ok(Subject::Label { unit, tok });
    }
    // `this@Outer`, `return@forEach`: the name of a class or of the function the lambda goes to.
    let hits = implicit_label_targets(an, unit, tok);
    if hits.is_empty() {
        return Err(format!("there is no label `{name}` here to rename"));
    }
    Ok(Subject::Group(features::rename_group(an, hits[0])))
}

/// The class or function that the label reference `tok` (`this@Outer`, `return@forEach`) names.
fn implicit_label_targets(an: &Analyzer, unit: UnitId, tok: usize) -> Vec<SymId> {
    let u = an.unit(unit);
    let (file, lx) = (&u.file, &u.file.lexed);
    let name = lx.text(&u.text, tok);
    let at = lx.tokens[tok].start;
    let mut out = Vec::new();
    for s in &file.scopes {
        if let super::syntax::ScopeKind::Lambda { brace, .. } = s.kind
            && s.range.contains(&at)
            && lx.kind(brace.wrapping_sub(1)) != Some(Tok::Label)
            && let Some(callee) = an.lambda_ctx(unit, brace).and_then(|c| c.callee)
            && !callee.lib
            && an.decl(callee).name == name
        {
            out.push(callee);
        }
    }
    if tok > 0
        && (lx.is(&u.text, tok - 1, "this") || lx.is(&u.text, tok - 1, "super"))
        && let Some(Ty::Class { sym, .. }) = an.this_ty(unit, lx.tokens[tok - 1].start, Some(name))
        && !sym.lib
        && an.decl(sym).name == name
    {
        out.push(sym);
    }
    out
}

/// The label references (`@name`) of `name` in a file.
fn label_refs(u: &super::index::Unit, name: &str) -> Vec<usize> {
    let lx = &u.file.lexed;
    (0..lx.tokens.len()).filter(|&i| lx.tokens[i].kind == Tok::LabelRef && lx.text(&u.text, i) == name).collect()
}

/// The tokens a label declared at `label` is in scope for: the code it labels.
fn label_region(lx: &Lexed, label: usize) -> Range<usize> {
    let mut open = Vec::new();
    for i in 0..label {
        match lx.kind(i) {
            Some(Tok::LBrace | Tok::TemplateOpen) => open.push(i),
            Some(Tok::RBrace) => {
                open.pop();
            }
            _ => {}
        }
    }
    let limit = open.last().and_then(|&o| lx.matching.get(o).copied().flatten()).unwrap_or(lx.tokens.len());
    let mut j = label + 1;
    while j < limit {
        match lx.kind(j) {
            Some(Tok::LParen | Tok::LBracket) => match lx.matching.get(j).copied().flatten() {
                Some(close) => j = close,
                None => break,
            },
            Some(Tok::LBrace) => return label + 1..lx.matching.get(j).copied().flatten().unwrap_or(limit),
            Some(Tok::Semi) => return label + 1..j,
            _ => {}
        }
        j += 1;
    }
    label + 1..limit
}

// ----- KDoc -----

/// A name in a KDoc comment: the segments of a link (`[a.B.c]`, `@see a.B`) or a parameter tag.
#[derive(Debug)]
pub(super) struct DocRef {
    pub segs: Vec<(String, Range<usize>)>,
    /// `@param name` and `@property name`.
    pub tag: bool,
}

/// The names the KDoc comment at `doc` mentions.
fn doc_refs(src: &str, doc: &Range<usize>) -> Vec<DocRef> {
    let mut out = Vec::new();
    let body = &src[doc.clone()];
    let is_path = |c: char| c.is_alphanumeric() || matches!(c, '_' | '.' | '`' | '$');
    let split = |path: &str, base: usize| -> Vec<(String, Range<usize>)> {
        let mut segs = Vec::new();
        let mut at = 0;
        for part in path.split('.') {
            if !part.is_empty() {
                segs.push((strip_ticks(part).to_owned(), base + at..base + at + part.len()));
            }
            at += part.len() + 1;
        }
        segs
    };
    // The tags.
    let mut line_start = 0;
    for line in body.split_inclusive('\n') {
        let indent = line.len() - line.trim_start_matches(|c: char| c.is_whitespace() || c == '*' || c == '/').len();
        let rest = &line[indent..];
        for (tag, is_param) in
            [("@param", true), ("@property", true), ("@see", false), ("@throws", false), ("@exception", false), ("@sample", false)]
        {
            let Some(after) = rest.strip_prefix(tag) else { continue };
            // `@param name` or `@param[name]`.
            let bracket = after.starts_with('[');
            if !bracket && !after.starts_with(char::is_whitespace) {
                continue;
            }
            let gap = if bracket { 1 } else { after.len() - after.trim_start().len() };
            let word = after[gap..].split(|c: char| !is_path(c)).next().unwrap_or_default();
            if word.is_empty() {
                continue;
            }
            let base = doc.start + line_start + indent + tag.len() + gap;
            let segs = if is_param { vec![(strip_ticks(word).to_owned(), base..base + word.len())] } else { split(word, base) };
            if !segs.is_empty() {
                out.push(DocRef { segs, tag: is_param });
            }
        }
        line_start += line.len();
    }
    // The links in brackets.
    let bytes = body.as_bytes();
    let mut i = 0;
    // Brackets in code spans and fences (`a[i]`) are not links.
    let mut in_code = false;
    while i < bytes.len() {
        if bytes[i] == b'`' {
            in_code = !in_code;
        }
        if bytes[i] == b'['
            && !in_code
            && let Some(len) = body[i + 1..].find([']', '\n', '[']).filter(|&n| bytes[i + 1 + n] == b']')
        {
            let content = &body[i + 1..i + 1 + len];
            let next = bytes.get(i + 2 + len).copied();
            let prev = body[..i].chars().next_back();
            let indexing = prev.is_some_and(|c| c.is_alphanumeric() || c == ')' || c == '_');
            if !content.is_empty()
                && content.chars().all(is_path)
                && !content.starts_with('.')
                && !content.ends_with('.')
                && !matches!(next, Some(b'[' | b'('))
                && !indexing
            {
                let segs = split(content, doc.start + i + 1);
                if !segs.is_empty() {
                    out.push(DocRef { segs, tag: false });
                }
            }
        }
        i += 1;
    }
    out
}

/// What a KDoc name is looked for as.
enum DocQuery<'a> {
    Syms(&'a [SymId]),
    Package(&'a str),
    TypeParam { owner: DeclId },
}

/// The ranges in the KDoc comments of `unit` that name `name` as `query` describes.
fn doc_hits(an: &Analyzer, unit: UnitId, query: &DocQuery, name: &str) -> Vec<Range<usize>> {
    let u = an.unit(unit);
    let file = &u.file;
    let mut out = Vec::new();
    for (di, d) in file.decls.iter().enumerate() {
        let Some(doc) = &d.doc else { continue };
        if !u.text[doc.clone()].contains(name) {
            continue;
        }
        for r in doc_refs(&u.text, doc) {
            for (j, (seg, range)) in r.segs.iter().enumerate() {
                if seg != name {
                    continue;
                }
                let hit = match query {
                    DocQuery::Syms(group) => resolve_ref(an, unit, di, &r, j).iter().any(|s| group.contains(s)),
                    DocQuery::Package(fq) => {
                        let path: Vec<&str> = r.segs[..=j].iter().map(|(s, _)| s.as_str()).collect();
                        !r.tag && path.join(".") == *fq
                    }
                    DocQuery::TypeParam { owner } => {
                        r.segs.len() == 1
                            && (di == *owner
                                || (!r.tag && d.span.start >= file.decls[*owner].span.start && d.span.end <= file.decls[*owner].span.end))
                    }
                };
                if hit {
                    out.push(range.clone());
                }
            }
        }
    }
    out
}

/// What segment `upto` of the KDoc name `r` in the comment of declaration `di` refers to.
pub(super) fn resolve_ref(an: &Analyzer, unit: UnitId, di: DeclId, r: &DocRef, upto: usize) -> Vec<SymId> {
    let file = an.file(unit);
    let d = &file.decls[di];
    let doc_end = d.doc.as_ref().map_or(d.span.start, |r| r.end);
    let own = |name: &str| -> Vec<SymId> {
        let mut out: Vec<SymId> = Vec::new();
        for &p in d.params.iter().chain(d.members.iter()) {
            if file.decls[p].name == name && !out.contains(&unit.sym(p)) {
                out.push(unit.sym(p));
            }
        }
        out
    };
    if r.tag {
        return own(&r.segs[0].0);
    }
    let mut cur: Vec<SymId> = Vec::new();
    for j in 0..=upto {
        let name = r.segs[j].0.as_str();
        if j == 0 {
            cur = own(name);
            if cur.is_empty() {
                cur = an
                    .resolve_name(unit, doc_end, name)
                    .into_iter()
                    .filter_map(|f| match f {
                        Found::Sym(m) => Some(m.sym),
                        Found::It { .. } => None,
                    })
                    .collect();
            }
            continue;
        }
        let path: Vec<&str> = r.segs[..=j].iter().map(|(s, _)| s.as_str()).collect();
        let qualified = an.by_fq(&path.join("."));
        cur = if qualified.is_empty() { members_of(an, unit, &cur, name) } else { qualified };
    }
    cur
}

fn members_of(an: &Analyzer, unit: UnitId, syms: &[SymId], name: &str) -> Vec<SymId> {
    let mut out: Vec<SymId> = Vec::new();
    for &s in syms {
        let d = an.decl(s);
        let types: Vec<Ty> = if d.kind.is_class() || d.kind == Kind::TypeAlias {
            vec![an.instance(s), Ty::Static(s)]
        } else {
            an.value_ty(s, &Subst::new()).into_iter().collect()
        };
        for ty in types {
            for m in an.members_named(&ty, name, unit) {
                if !out.contains(&m.sym) {
                    out.push(m.sym);
                }
            }
        }
    }
    out
}

/// The subject of a name in a KDoc comment under the cursor.
fn doc_subject(an: &Analyzer, unit: UnitId, offset: usize) -> Result<Selection, String> {
    let u = an.unit(unit);
    for (di, d) in u.file.decls.iter().enumerate() {
        let Some(doc) = &d.doc else { continue };
        if !(doc.start <= offset && offset <= doc.end) {
            continue;
        }
        for r in doc_refs(&u.text, doc) {
            for (j, (name, range)) in r.segs.iter().enumerate() {
                if range.start <= offset && offset <= range.end {
                    let group: Vec<SymId> = resolve_ref(an, unit, di, &r, j).into_iter().filter(|s| !s.lib).collect();
                    let Some(&first) = group.first() else {
                        let path: Vec<&str> = r.segs[..=j].iter().map(|(s, _)| s.as_str()).collect();
                        let fq = path.join(".");
                        if project_has_package(an, &fq) && !r.tag {
                            return Ok(Selection { subject: Subject::Package(fq), span: range.clone(), placeholder: name.clone() });
                        }
                        if r.segs.len() == 1 && d.type_params.iter().any(|p| strip_ticks(&p.name) == name) {
                            let index = d.type_params.iter().position(|p| strip_ticks(&p.name) == name).unwrap_or(0);
                            return Ok(Selection {
                                subject: Subject::TypeParam { unit, owner: di, index },
                                span: range.clone(),
                                placeholder: name.clone(),
                            });
                        }
                        return Err(format!("`{name}` doesn't refer to a declaration of this project"));
                    };
                    if an.unit(first.unit_id()).is_java() || an.decl(first).generated {
                        return Err(format!("`{name}` can't be renamed here"));
                    }
                    return Ok(Selection {
                        subject: Subject::Group(features::rename_group(an, first)),
                        span: range.clone(),
                        placeholder: name.clone(),
                    });
                }
            }
        }
    }
    Err("there is nothing to rename here".into())
}

// ----- the plan -----

/// A change to a `kargo.toml`.
#[derive(Debug)]
enum ManifestChange {
    /// A declaration named by an entry point, and what it is called now.
    Entry(String, String),
    /// A file that a `[[bin]]` has as its `path`.
    BinPath(PathBuf, PathBuf),
}

/// Everything one rename changes.
#[derive(Debug, Default)]
struct Plan {
    edits: BTreeMap<UnitId, Vec<(Range<usize>, String)>>,
    manifest: Vec<ManifestChange>,
    renames: Vec<(PathBuf, PathBuf)>,
}

fn cancelled() -> String {
    "the request was cancelled".into()
}

impl Plan {
    fn replace(&mut self, unit: UnitId, range: Range<usize>, text: &str) {
        self.edits.entry(unit).or_default().push((range, text.to_owned()));
    }

    /// Renames declarations of the project, with the KDoc names, labels, file and entry points
    /// that go with them. `move_files` renames the file named after a class too.
    fn group(
        &mut self,
        an: &Analyzer,
        env: &Env,
        group: &[SymId],
        new_name: &str,
        control: &Control,
        move_files: bool,
    ) -> Result<(), String> {
        let new_text = features::new_name_text(new_name).ok_or_else(|| format!("`{new_name}` is not a valid Kotlin name"))?;
        let bare = strip_ticks(&new_text).to_owned();
        for (unit, range) in features::search(an, group, true, control).ok_or_else(cancelled)? {
            self.replace(unit, range, &new_text);
        }
        let Some(&first) = group.first() else { return Ok(()) };
        let old = an.decl(first).name.clone();
        for (ui, _) in an.proj.units.iter().enumerate() {
            let uid = UnitId { lib: false, unit: ui as u32 };
            if an.unit(uid).is_java() {
                continue;
            }
            for range in doc_hits(an, uid, &DocQuery::Syms(group), &old) {
                self.replace(uid, range, &new_text);
            }
            // `this@Outer` and `return@forEach` name the class or the function.
            let u = an.unit(uid);
            for i in label_refs(u, &old) {
                if implicit_label_targets(an, uid, i).iter().any(|s| group.contains(s)) {
                    self.replace(uid, u.file.lexed.tokens[i].span(), &new_text);
                }
            }
        }
        for &sym in group {
            self.declaration_entries(an, sym, &bare);
        }
        if move_files && env.rename_files && env.can_rename() {
            for &sym in group {
                self.file_of(an, sym, &old, &bare);
            }
        }
        Ok(())
    }

    /// The entry points that name the declaration `sym`.
    fn declaration_entries(&mut self, an: &Analyzer, sym: SymId, new: &str) {
        let (file, d) = (an.file(sym.unit_id()), an.decl(sym));
        let top_level = d.parent.is_none();
        if !(d.kind.is_class() || d.kind == Kind::TypeAlias || (d.kind == Kind::Function && top_level)) {
            return;
        }
        let dotted = file.fq_name(sym.decl_id());
        let renamed = |name: &str| match name.rsplit_once('.') {
            Some((head, _)) => format!("{head}.{new}"),
            None => new.to_owned(),
        };
        self.manifest.push(ManifestChange::Entry(dotted.clone(), renamed(&dotted)));
        if !top_level && d.kind.is_class() {
            // Nested classes are `Outer$Inner` for the JVM.
            let mut names = vec![d.name.as_str()];
            let mut p = d.parent;
            while let Some(pid) = p {
                names.push(&file.decls[pid].name);
                p = file.decls[pid].parent;
            }
            names.reverse();
            let binary = |last: &str| {
                let mut names = names.clone();
                *names.last_mut().unwrap() = last;
                let joined = names.join("$");
                if file.package.is_empty() { joined } else { format!("{}.{joined}", file.package) }
            };
            self.manifest.push(ManifestChange::Entry(binary(&d.name), binary(new)));
        }
    }

    /// Renames the file of the class `sym` when it is named after it (`User.kt`, `User.jvm.kt`).
    fn file_of(&mut self, an: &Analyzer, sym: SymId, old: &str, new: &str) {
        let d = an.decl(sym);
        if d.parent.is_some() || !(d.kind.is_class() || d.kind == Kind::TypeAlias) {
            return;
        }
        let uid = sym.unit_id();
        let path = &an.unit(uid).path;
        let Some(stem) = path.file_stem().map(|s| s.to_string_lossy().into_owned()) else { return };
        let extension = path.extension().map(|e| e.to_string_lossy().into_owned()).unwrap_or_default();
        let named_after = stem == old || stem.strip_prefix(old).is_some_and(|rest| rest.starts_with('.'));
        if !named_after || !plain_name(new) {
            return;
        }
        let renamed = path.with_file_name(format!("{new}{}.{extension}", &stem[old.len()..]));
        if renamed.exists() || an.proj.units.iter().any(|u| u.path == renamed) || self.renames.iter().any(|(a, _)| a == path) {
            return;
        }
        let new_stem = format!("{new}{}", &stem[old.len()..]);
        self.file_class(an, uid, &stem, &new_stem);
        self.renames.push((path.clone(), renamed));
    }

    /// The class the top-level members of a file compile to (`MainKt`) and the `path` of a
    /// `[[bin]]` change with its name.
    fn file_class(&mut self, an: &Analyzer, unit: UnitId, old_stem: &str, new_stem: &str) {
        let u = an.unit(unit);
        if !u.text.contains("@file:JvmName") && !u.text.contains("@file:kotlin.jvm.JvmName") {
            let qualify = |stem: &str| {
                let class = file_class(stem);
                if u.file.package.is_empty() { class } else { format!("{}.{class}", u.file.package) }
            };
            self.manifest.push(ManifestChange::Entry(qualify(old_stem), qualify(new_stem)));
        }
        let extension = u.path.extension().map(|e| e.to_string_lossy().into_owned()).unwrap_or_default();
        self.manifest.push(ManifestChange::BinPath(u.path.clone(), u.path.with_file_name(format!("{new_stem}.{extension}"))));
    }

    /// Renames the package `old_fq` to `new_name` in the same parent: its directives, imports,
    /// qualified names and KDoc, the entry points, and the directories.
    fn package(
        &mut self,
        an: &Analyzer,
        env: &Env,
        old_fq: &str,
        new_name: &str,
        control: &Control,
        move_dirs: bool,
    ) -> Result<(), String> {
        let new_text = features::new_name_text(new_name).ok_or_else(|| format!("`{new_name}` is not a valid Kotlin name"))?;
        let bare = strip_ticks(&new_text).to_owned();
        let (parent, old) = old_fq.rsplit_once('.').unwrap_or(("", old_fq));
        let new_fq = if parent.is_empty() { bare.clone() } else { format!("{parent}.{bare}") };
        if project_has_package(an, &new_fq) {
            return Err(format!("the package `{new_fq}` exists already"));
        }
        for (ui, unit) in an.proj.units.iter().enumerate() {
            if control.cancelled.is_some_and(|c| c()) {
                return Err(cancelled());
            }
            let uid = UnitId { lib: false, unit: ui as u32 };
            if unit.is_java() {
                continue;
            }
            for &i in unit.ident_tokens(old) {
                if matches!(features::targets_at(an, uid, i).first(), Some(Target::Package(p)) if p == old_fq) {
                    self.replace(uid, unit.file.lexed.tokens[i].span(), &new_text);
                }
            }
            for range in doc_hits(an, uid, &DocQuery::Package(old_fq), old) {
                self.replace(uid, range, &new_text);
            }
        }
        self.manifest.push(ManifestChange::Entry(old_fq.to_owned(), new_fq));
        if move_dirs && env.can_rename() && env.move_directories {
            let relative: PathBuf = old_fq.split('.').collect();
            let mut seen: Vec<PathBuf> = Vec::new();
            for root in &env.roots {
                let dir = root.join(&relative);
                if seen.contains(&dir) || !dir.is_dir() {
                    continue;
                }
                seen.push(dir.clone());
                let target = dir.with_file_name(&bare);
                // Only a directory that holds the package and nothing else moves.
                let inside = an.proj.units.iter().filter(|u| u.path.starts_with(&dir));
                if target.exists() || !inside.clone().all(|u| in_package(&u.file.package, old_fq)) || inside.count() == 0 {
                    continue;
                }
                self.renames.push((dir, target));
            }
        }
        Ok(())
    }

    /// Renames type parameter `index` of `owner`.
    fn type_param(&mut self, an: &Analyzer, unit: UnitId, owner: DeclId, index: usize, new_name: &str) -> Result<(), String> {
        let new_text = features::new_name_text(new_name).ok_or_else(|| format!("`{new_name}` is not a valid Kotlin name"))?;
        let name = strip_ticks(&an.file(unit).decls[owner].type_params[index].name).to_owned();
        for range in type_param_tokens(an, unit, owner, index) {
            self.replace(unit, range, &new_text);
        }
        for range in doc_hits(an, unit, &DocQuery::TypeParam { owner }, &name) {
            self.replace(unit, range, &new_text);
        }
        Ok(())
    }

    /// Renames the label declared at token `tok` and the references to it.
    fn label(&mut self, an: &Analyzer, unit: UnitId, tok: usize, new_name: &str) -> Result<(), String> {
        if !plain_name(new_name) {
            return Err(format!("`{new_name}` is not a valid label"));
        }
        let u = an.unit(unit);
        let lx = &u.file.lexed;
        let name = lx.text(&u.text, tok);
        self.replace(unit, lx.tokens[tok].span(), new_name);
        for i in label_region(lx, tok) {
            if lx.kind(i) == Some(Tok::LabelRef) && lx.text(&u.text, i) == name {
                // A label of the same name inside shadows this one.
                let shadowed =
                    (tok + 1..i).any(|k| lx.kind(k) == Some(Tok::Label) && lx.text(&u.text, k) == name && label_region(lx, k).contains(&i));
                if !shadowed {
                    self.replace(unit, lx.tokens[i].span(), new_name);
                }
            }
        }
        Ok(())
    }

    /// The `WorkspaceEdit` of the plan.
    fn finish(self, an: &Analyzer, env: &Env) -> Value {
        let mut files: Vec<(PathBuf, Vec<Value>)> = Vec::new();
        for (uid, mut edits) in self.edits {
            let unit = an.unit(uid);
            edits.sort_by(|a, b| a.0.start.cmp(&b.0.start).then(a.0.end.cmp(&b.0.end)));
            edits.dedup_by(|b, a| a.0 == b.0);
            let mut last_end = 0;
            let json: Vec<Value> = edits
                .into_iter()
                .filter(|(range, _)| {
                    let keep = range.start >= last_end;
                    if keep {
                        last_end = range.end;
                    }
                    keep
                })
                .map(|(range, text)| json!({ "range": text::range(&unit.text, range), "newText": text }))
                .collect();
            files.push((unit.path.clone(), json));
        }
        for manifest in &env.manifests {
            if let Some(edit) = manifest_edit(manifest, &self.manifest) {
                files.push((manifest.clone(), vec![edit]));
            }
        }
        if !env.document_changes {
            let map: serde_json::Map<String, Value> = files.into_iter().map(|(p, e)| (text::path_to_uri(&p), json!(e))).collect();
            return json!({ "changes": map });
        }
        let mut list: Vec<Value> = files
            .into_iter()
            .map(|(path, edits)| {
                let version = env.versions.get(&path).map_or(Value::Null, |v| json!(v));
                json!({ "textDocument": { "uri": text::path_to_uri(&path), "version": version }, "edits": edits })
            })
            .collect();
        if env.resource_renames {
            for (old, new) in &self.renames {
                list.push(json!({ "kind": "rename", "oldUri": text::path_to_uri(old), "newUri": text::path_to_uri(new) }));
            }
        }
        json!({ "documentChanges": list })
    }
}

/// The edit of the `kargo.toml` at `path` for `changes`, if any entry changes.
fn manifest_edit(path: &Path, changes: &[ManifestChange]) -> Option<Value> {
    if changes.is_empty() {
        return None;
    }
    let old = std::fs::read_to_string(path).ok()?;
    let mut editor = ManifestEditor::from_str(path, &old).ok()?;
    let dir = path.parent().unwrap_or(Path::new(""));
    let mut changed = 0;
    for change in changes {
        changed += match change {
            ManifestChange::Entry(from, to) => editor.rename_entry_points(from, to),
            ManifestChange::BinPath(from, to) => {
                let relative = |p: &Path| p.strip_prefix(dir).ok().map(|r| r.to_string_lossy().replace('\\', "/"));
                match (relative(from), relative(to)) {
                    (Some(from), Some(to)) => editor.rename_bin_path(&from, &to),
                    _ => 0,
                }
            }
        };
    }
    if changed == 0 {
        return None;
    }
    text::edit(&old, &editor.contents())
}

/// The name of the class a file's top-level members compile to: `Main.kt` gives `MainKt`.
fn file_class(stem: &str) -> String {
    let mut name: String = stem.chars().map(|c| if lexer::is_ident_char(c) { c } else { '_' }).collect();
    if let Some(first) = name.chars().next() {
        let upper: String = first.to_uppercase().collect();
        name.replace_range(..first.len_utf8(), &upper);
    }
    name + "Kt"
}

/// Whether `name` is an identifier without backquotes.
fn plain_name(name: &str) -> bool {
    name.chars().next().is_some_and(lexer::is_ident_start)
        && name.chars().all(lexer::is_ident_char)
        && !lexer::HARD_KEYWORDS.contains(&name)
}

/// The edit that renames `found` to `new_name`.
pub fn rename(an: &Analyzer, env: &Env, found: &Selection, new_name: &str, control: &Control) -> Result<Value, String> {
    let mut plan = Plan::default();
    match &found.subject {
        Subject::Group(group) => plan.group(an, env, group, new_name, control, true)?,
        Subject::Package(fq) => plan.package(an, env, fq, strip_ticks(new_name.trim()), control, true)?,
        Subject::TypeParam { unit, owner, index } => plan.type_param(an, *unit, *owner, *index, new_name)?,
        Subject::Label { unit: label_unit, tok } => plan.label(an, *label_unit, *tok, new_name.trim())?,
    }
    Ok(plan.finish(an, env))
}

/// The edit for `workspace/willRenameFiles`: renaming `Name.kt` renames the class `Name`, and
/// renaming a package's directory renames the package. `Null` when nothing follows.
pub fn will_rename(an: &Analyzer, env: &Env, files: &[(PathBuf, PathBuf)], control: &Control) -> Result<Value, String> {
    let mut plan = Plan::default();
    for (old, new) in files {
        if old.parent() != new.parent() {
            continue;
        }
        let (Some(from), Some(to)) = (old.file_name(), new.file_name()) else { continue };
        let (from, to) = (from.to_string_lossy().into_owned(), to.to_string_lossy().into_owned());
        if old.is_dir() {
            // A package's directory.
            let Some(root) = env.roots.iter().find(|r| old.starts_with(r) && *r != old) else { continue };
            let Ok(relative) = old.strip_prefix(root) else { continue };
            let mut segments: Vec<String> = relative.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect();
            let fq = segments.join(".");
            segments.pop();
            segments.push(to.clone());
            if plain_name(&to) && project_has_package(an, &fq) && !project_has_package(an, &segments.join(".")) {
                plan.package(an, env, &fq, &to, control, false)?;
            }
            continue;
        }
        let (Some(old_stem), Some(new_stem)) = (from.strip_suffix(".kt"), to.strip_suffix(".kt")) else { continue };
        let Some(ui) = an.proj.units.iter().position(|u| &u.path == old) else { continue };
        let uid = UnitId { lib: false, unit: ui as u32 };
        let file = an.file(uid);
        if plain_name(new_stem) {
            let class = file.top.iter().copied().find(|&t| {
                let d = &file.decls[t];
                (d.kind.is_class() || d.kind == Kind::TypeAlias) && d.name == old_stem && !d.generated
            });
            if let Some(class) = class {
                let group = features::rename_group(an, uid.sym(class));
                plan.group(an, env, &group, new_stem, control, false)?;
            }
        }
        plan.file_class(an, uid, old_stem, new_stem);
    }
    let edit = plan.finish(an, env);
    let empty = edit["documentChanges"].as_array().is_some_and(Vec::is_empty) || edit["changes"].as_object().is_some_and(|c| c.is_empty());
    Ok(if empty { Value::Null } else { edit })
}
