//! `kargo.lock`: pins every resolved module version and artifact checksum so
//! builds are reproducible and tampered downloads are detected.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use kargo_maven::coord::ModuleId;
use kargo_maven::repo::MavenClient;
use kargo_maven::resolver::{Resolution, ResolvedNode};
use kargo_util::hash;

const LOCKFILE_VERSION: u32 = 1;
const HEADER: &str = "# This file is automatically generated by Kargo.\n# It is not intended for manual editing.\n";

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    /// Keyed by resolution name, e.g. `jvm/runtime`.
    #[serde(default, rename = "resolution")]
    pub resolutions: BTreeMap<String, LockedResolution>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedResolution {
    /// Fingerprint of everything that influenced the resolution.
    pub inputs: String,
    pub roots: Vec<String>,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub module: String,
    pub version: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub files: Vec<LockedFile>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedFile {
    /// Repository-relative path.
    pub path: String,
    pub sha256: String,
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Self> {
        if !path.is_file() {
            return Ok(Self { version: LOCKFILE_VERSION, ..Default::default() });
        }
        let text = std::fs::read_to_string(path).with_context(|| format!("failed to read {}", path.display()))?;
        let lock: Lockfile =
            toml::from_str(&text).with_context(|| format!("failed to parse {}; delete it to regenerate", path.display()))?;
        if lock.version != LOCKFILE_VERSION {
            bail!("{} has unsupported version {}; delete it to regenerate", path.display(), lock.version);
        }
        Ok(lock)
    }

    pub fn to_toml(&self) -> Result<String> {
        Ok(format!("{HEADER}{}", toml::to_string(self)?))
    }

    /// Writes the lockfile only if its content changed.
    pub fn save(&self, path: &Path) -> Result<bool> {
        let text = self.to_toml()?;
        if std::fs::read_to_string(path).ok().as_deref() == Some(text.as_str()) {
            return Ok(false);
        }
        kargo_util::fs::write_string_atomic(path, &text)?;
        Ok(true)
    }

    /// Records a fresh resolution, hashing each artifact. Artifacts that were already cached are
    /// first checked against their repository's checksum (and re-downloaded if corrupt), so a bad
    /// cached file is never pinned.
    pub fn record(&mut self, key: &str, inputs: &str, resolution: &Resolution, client: &MavenClient) -> Result<()> {
        let cache_dir = client.cache_dir();
        let packages = resolution
            .nodes
            .iter()
            .map(|node| {
                let files = node
                    .files
                    .iter()
                    .map(|file| {
                        let rel = file
                            .strip_prefix(cache_dir)
                            .map(|p| p.to_string_lossy().replace('\\', "/"))
                            .with_context(|| format!("{} is outside the Kargo cache", file.display()))?;
                        let file = client.fetch_verified(&rel)?;
                        let sha256 = hash::sha256_file(&file).with_context(|| format!("failed to hash {}", file.display()))?;
                        Ok(LockedFile { path: rel, sha256 })
                    })
                    .collect::<Result<Vec<_>>>()?;
                Ok(LockedPackage {
                    module: node.module.to_string(),
                    version: node.version.clone(),
                    // `group:artifact[:requested-version]`
                    dependencies: node
                        .dependencies
                        .iter()
                        .map(|(m, req)| match req {
                            Some(v) => format!("{m}:{v}"),
                            None => m.to_string(),
                        })
                        .collect(),
                    files,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        self.resolutions.insert(
            key.to_owned(),
            LockedResolution { inputs: inputs.to_owned(), roots: resolution.roots.iter().map(ToString::to_string).collect(), packages },
        );
        Ok(())
    }

    /// Reuses a locked resolution if its inputs match, re-downloading any
    /// missing artifact and verifying its checksum.
    pub fn restore(&self, key: &str, inputs: &str, client: &MavenClient) -> Result<Option<Resolution>> {
        let Some(locked) = self.resolutions.get(key) else { return Ok(None) };
        if locked.inputs != inputs {
            return Ok(None);
        }
        for pkg in &locked.packages {
            for file in &pkg.files {
                if kargo_maven::repo::resolve_relative("", &file.path).ok().as_deref() != Some(file.path.as_str()) {
                    bail!("corrupt lockfile: suspicious artifact path `{}`", file.path);
                }
            }
        }
        let local = |path: &str| path.split('/').fold(client.cache_dir().to_path_buf(), |p, seg| p.join(seg));
        // Download whatever is missing from the cache in parallel (a fresh CI machine has nothing).
        let missing: Vec<&LockedFile> = locked.packages.iter().flat_map(|p| &p.files).filter(|f| !local(&f.path).is_file()).collect();
        let downloaded: Vec<Result<(PathBuf, String)>> = kargo_maven::par_map_io(&missing, |file| {
            let fetched = client.fetch_required(&file.path)?;
            let actual = hash::sha256_file(&fetched)?;
            Ok((fetched, actual))
        });
        let mut downloaded: std::collections::HashMap<&str, Result<(PathBuf, String)>> =
            missing.iter().map(|f| f.path.as_str()).zip(downloaded).collect();

        let mut nodes = Vec::with_capacity(locked.packages.len());
        for pkg in &locked.packages {
            let module: ModuleId = pkg.module.parse().with_context(|| format!("corrupt lockfile entry `{}`", pkg.module))?;
            let mut files: Vec<PathBuf> = Vec::new();
            for file in &pkg.files {
                let Some(result) = downloaded.remove(file.path.as_str()) else {
                    files.push(local(&file.path));
                    continue;
                };
                let (fetched, actual) = result?;
                if actual != file.sha256 {
                    let verified = client.is_verified(&file.path);
                    let _ = std::fs::remove_file(&fetched);
                    let cause = if verified {
                        "the downloaded file matches the checksum its repository publishes, so the kargo.lock entry is likely wrong \
                         (for example, it was recorded from a corrupt cached file); if you trust the repository, run `kargo update` to re-lock it"
                    } else {
                        "the repository publishes no checksum to tell which side is wrong: either the artifact changed upstream or was \
                         tampered with, or the kargo.lock entry is wrong; run `kargo update` to re-lock it only if you trust the repository"
                    };
                    bail!("checksum mismatch for {} (locked sha256 {}, downloaded {actual}); {cause}", file.path, file.sha256);
                }
                files.push(fetched);
            }
            let dependencies = pkg
                .dependencies
                .iter()
                .map(|d| parse_locked_dependency(d))
                .collect::<Result<Vec<_>>>()
                .with_context(|| format!("corrupt lockfile dependencies for `{}`", pkg.module))?;
            nodes.push(ResolvedNode { module, version: pkg.version.clone(), files, dependencies });
        }
        let roots = locked.roots.iter().map(|r| r.parse()).collect::<Result<Vec<ModuleId>, _>>().context("corrupt lockfile roots")?;
        Ok(Some(Resolution { roots, nodes }))
    }

    /// Drops resolutions not in `keep` (e.g. after a target is removed).
    pub fn retain(&mut self, keep: &[String]) {
        self.resolutions.retain(|k, _| keep.contains(k));
    }

    /// Every locked version of each module, across all resolutions.
    pub fn module_versions(&self) -> BTreeMap<String, BTreeSet<String>> {
        let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
        for pkg in self.resolutions.values().flat_map(|r| &r.packages) {
            out.entry(pkg.module.clone()).or_default().insert(pkg.version.clone());
        }
        out
    }

    /// Whether any resolution locks `module` (`group:artifact`).
    pub fn contains_module(&self, module: &str) -> bool {
        self.resolutions.values().flat_map(|r| &r.packages).any(|p| p.module == module)
    }

    /// The modules whose locked versions differ between `self` and `newer`.
    pub fn diff(&self, newer: &Lockfile) -> Vec<LockChange> {
        let (old, new) = (self.module_versions(), newer.module_versions());
        let modules: BTreeSet<&String> = old.keys().chain(new.keys()).collect();
        modules
            .into_iter()
            .filter_map(|module| {
                let before: Vec<String> = old.get(module).map(|v| v.iter().cloned().collect()).unwrap_or_default();
                let after: Vec<String> = new.get(module).map(|v| v.iter().cloned().collect()).unwrap_or_default();
                (before != after).then(|| LockChange { module: module.clone(), before, after })
            })
            .collect()
    }
}

/// One module whose locked versions changed (empty `before`: added; empty `after`: removed).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockChange {
    pub module: String,
    pub before: Vec<String>,
    pub after: Vec<String>,
}

/// Parses `group:artifact[:requested-version]`; versions may contain `:` only in ranges, which never do.
fn parse_locked_dependency(entry: &str) -> Result<(ModuleId, Option<String>)> {
    let mut parts = entry.splitn(3, ':');
    let (Some(group), Some(artifact)) = (parts.next(), parts.next()) else {
        bail!("invalid dependency entry `{entry}`");
    };
    let module: ModuleId = format!("{group}:{artifact}").parse()?;
    Ok((module, parts.next().map(str::to_owned)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use kargo_maven::repo::Repository;
    use kargo_util::config::Config;
    use kargo_util::shell::{Shell, Verbosity};

    fn setup() -> (tempfile::TempDir, tempfile::TempDir, MavenClient, Resolution) {
        let repo = tempfile::tempdir().unwrap();
        let home = tempfile::tempdir().unwrap();
        let rel = "g/a/1.0/a-1.0.jar";
        std::fs::create_dir_all(repo.path().join("g/a/1.0")).unwrap();
        std::fs::write(repo.path().join(rel), "jar-bytes").unwrap();
        let config = Config::new(home.path().to_path_buf(), Shell::new(Verbosity::Quiet));
        let client = MavenClient::new(&config, vec![Repository::new("r", format!("file://{}", repo.path().display()))]);
        let file = client.fetch_required(rel).unwrap();
        let resolution = Resolution {
            roots: vec!["g:a".parse().unwrap()],
            nodes: vec![ResolvedNode {
                module: "g:a".parse().unwrap(),
                version: "1.0".into(),
                files: vec![file],
                dependencies: vec![("g:b".parse().unwrap(), Some("2".into()))],
            }],
        };
        (repo, home, client, resolution)
    }

    #[test]
    fn round_trip_and_restore() {
        let (_repo, _home, client, resolution) = setup();
        let mut lock = Lockfile { version: LOCKFILE_VERSION, ..Default::default() };
        lock.record("jvm/runtime", "abc", &resolution, &client).unwrap();
        let text = lock.to_toml().unwrap();
        assert!(text.starts_with(HEADER));
        assert!(text.contains("g/a/1.0/a-1.0.jar"), "{text}");

        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("kargo.lock");
        assert!(lock.save(&path).unwrap());
        assert!(!lock.save(&path).unwrap(), "unchanged lockfile is not rewritten");
        let loaded = Lockfile::load(&path).unwrap();
        assert_eq!(loaded, lock);

        let restored = loaded.restore("jvm/runtime", "abc", &client).unwrap().unwrap();
        assert_eq!(restored.nodes[0].files, resolution.nodes[0].files);
        assert_eq!(restored.nodes[0].dependencies[0], ("g:b".parse().unwrap(), Some("2".to_owned())));
        assert!(loaded.restore("jvm/runtime", "different", &client).unwrap().is_none());
        assert!(loaded.restore("missing", "abc", &client).unwrap().is_none());
    }

    #[test]
    fn detects_tampered_artifacts() {
        let (repo, _home, client, resolution) = setup();
        let mut lock = Lockfile::default();
        lock.record("k", "i", &resolution, &client).unwrap();
        // Remove from cache and change upstream content.
        std::fs::remove_file(&resolution.nodes[0].files[0]).unwrap();
        std::fs::write(repo.path().join("g/a/1.0/a-1.0.jar"), "evil").unwrap();
        let fresh_client = {
            let home = client.cache_dir().parent().unwrap().parent().unwrap().to_path_buf();
            let config = Config::new(home, Shell::new(Verbosity::Quiet));
            MavenClient::new(&config, vec![Repository::new("r", format!("file://{}", repo.path().display()))])
        };
        let err = lock.restore("k", "i", &fresh_client).unwrap_err();
        assert!(err.to_string().contains("checksum mismatch"), "{err}");
        assert!(err.to_string().contains("kargo.lock entry is likely wrong"), "{err}");
    }

    #[test]
    fn record_does_not_lock_corrupt_cached_files() {
        let (_repo, _home, client, resolution) = setup();
        let mut good = Lockfile::default();
        good.record("k", "i", &resolution, &client).unwrap();

        let fresh_client = {
            let home = client.cache_dir().parent().unwrap().parent().unwrap().to_path_buf();
            let config = Config::new(home, Shell::new(Verbosity::Quiet));
            MavenClient::new(&config, client.repositories().to_vec())
        };
        std::fs::write(&resolution.nodes[0].files[0], "truncated").unwrap();
        let mut lock = Lockfile::default();
        lock.record("k", "i", &resolution, &fresh_client).unwrap();
        assert_eq!(lock, good);
        assert_eq!(std::fs::read_to_string(&resolution.nodes[0].files[0]).unwrap(), "jar-bytes");
    }

    #[test]
    fn missing_lockfile_is_empty_and_bad_versions_fail() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("kargo.lock");
        assert!(Lockfile::load(&path).unwrap().resolutions.is_empty());
        std::fs::write(&path, "version = 99\n").unwrap();
        assert!(Lockfile::load(&path).is_err());
        std::fs::write(&path, "garbage =").unwrap();
        assert!(Lockfile::load(&path).is_err());
    }

    #[test]
    fn locked_dependency_entries() {
        assert_eq!(parse_locked_dependency("a:b").unwrap(), ("a:b".parse().unwrap(), None));
        assert_eq!(parse_locked_dependency("a:b:[1.0,2.0)").unwrap().1.as_deref(), Some("[1.0,2.0)"));
        assert!(parse_locked_dependency("nonsense").is_err());
    }

    #[test]
    fn diff_lists_changed_modules() {
        let pkg = |m: &str, v: &str| LockedPackage { module: m.into(), version: v.into(), ..Default::default() };
        let lock = |pkgs: Vec<LockedPackage>| {
            let mut l = Lockfile::default();
            l.resolutions.insert("jvm/runtime".into(), LockedResolution { packages: pkgs, ..Default::default() });
            l
        };
        let old = lock(vec![pkg("g:a", "1.0"), pkg("g:b", "1.0"), pkg("g:gone", "1.0")]);
        let new = lock(vec![pkg("g:a", "1.1"), pkg("g:b", "1.0"), pkg("g:new", "2.0")]);
        assert!(old.contains_module("g:gone") && !new.contains_module("g:gone"));
        let changes = old.diff(&new);
        assert_eq!(
            changes,
            [
                LockChange { module: "g:a".into(), before: vec!["1.0".into()], after: vec!["1.1".into()] },
                LockChange { module: "g:gone".into(), before: vec!["1.0".into()], after: vec![] },
                LockChange { module: "g:new".into(), before: vec![], after: vec!["2.0".into()] },
            ]
        );
        assert!(new.diff(&new).is_empty());
    }

    #[test]
    fn retain_prunes() {
        let mut lock = Lockfile::default();
        lock.resolutions.insert("a".into(), LockedResolution::default());
        lock.resolutions.insert("b".into(), LockedResolution::default());
        lock.retain(&["b".to_owned()]);
        assert_eq!(lock.resolutions.keys().collect::<Vec<_>>(), ["b"]);
    }
}
