//! `kargo package --dist`: an application distribution, the `distZip` / `distTar` of Gradle's
//! `application` plugin.
//!
//! `target/dist/<name>-<version>/` holds `bin/<program>` (POSIX shell) and `bin/<program>.bat`
//! start scripts, `lib/` with the program's jar and the runtime dependencies, the README, LICENSE
//! and NOTICE files of the project and the `[package.dist] include` paths. Archives of that
//! directory (`.zip`, `.tar`, `.tar.gz`) sit next to it. The scripts find Java through `JAVA_HOME`,
//! then `PATH`.
//!
//! With a bundled runtime (`[package.dist] runtime = "jlink"`, `--bundle-runtime`) the distribution
//! also holds `runtime/`, a Java runtime trimmed by `jlink` as [`super::packaging`]'s jlink image
//! builds it, and the scripts prefer it over `JAVA_HOME` and `PATH`. `--platform` builds one
//! distribution per OS/CPU, each with that platform's runtime, in `<name>-<version>-<platform>/`.
//!
//! Archives are reproducible: entries sorted by path, a fixed timestamp, no owners and the same
//! file modes on every host (start scripts and the runtime's launchers 0755, everything else 0644).

use std::fs::File;
use std::io::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use super::build::JvmBuild;
use super::context::BuildContext;
use super::packaging::{App, app_jvm_args, bat_quote, jlink, runtime_modules, sh_quote};
use kargo_manifest::TargetPlatform;
use kargo_util::fs::remove_dir_all_if_exists;

/// An archive format of a distribution (`--archive`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Archive {
    Zip,
    Tar,
    TarGz,
}

impl Archive {
    /// The archives `kargo package --dist` writes when `--archive` is not given.
    pub const DEFAULT: [Archive; 2] = [Archive::Zip, Archive::TarGz];

    pub fn extension(self) -> &'static str {
        match self {
            Archive::Zip => "zip",
            Archive::Tar => "tar",
            Archive::TarGz => "tar.gz",
        }
    }
}

/// The Java runtime of a distribution.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Runtime<'a> {
    /// None: the start scripts find Java through `JAVA_HOME`, then `PATH`.
    System,
    /// A `jlink` runtime in `runtime/`: one distribution for the host, or one for each of the platforms.
    Jlink(&'a [TargetPlatform]),
}

/// A start script of the distribution: `bin/<name>` runs `main_class`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Program {
    pub name: String,
    pub main_class: String,
}

/// The environment variable with extra JVM options for a start script: `my-app` reads `MY_APP_OPTS`.
fn opts_variable(program: &str) -> String {
    let mut name: String = program.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' }).collect();
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert(0, '_');
    }
    format!("{name}_OPTS")
}

/// `bin/<program>`: finds Java (the bundled `runtime/`, then `JAVA_HOME`, then `PATH`), follows symlinks to
/// itself and runs the program's classpath from `lib/` with the JVM args, `JAVA_OPTS` and `<PROGRAM>_OPTS`.
fn unix_script(program: &Program, jvm_args: &[String], jars: &[String], bundled: bool) -> String {
    let classpath: Vec<String> = jars.iter().map(|j| format!("$APP_HOME/lib/{j}")).collect();
    let args: String = jvm_args.iter().map(|a| format!("{} ", sh_quote(a))).collect();
    let opts = opts_variable(&program.name);
    // The bundled runtime is the first branch of the chain that ends with `JAVA_HOME` and `PATH`.
    let runtime = if bundled { "if [ -x \"$APP_HOME/runtime/bin/java\" ]; then\n    JAVACMD=$APP_HOME/runtime/bin/java\nel" } else { "" };
    format!(
        r#"#!/bin/sh
# Generated by Kargo.
app_path=$0
while [ -h "$app_path" ]; do
    ls=$(ls -ld "$app_path")
    link=${{ls#*' -> '}}
    case $link in
        /*) app_path=$link ;;
        *) app_path=$(dirname "$app_path")/$link ;;
    esac
done
APP_HOME=$(cd "$(dirname "$app_path")/.." && pwd -P) || exit
{runtime}if [ -n "$JAVA_HOME" ]; then
    JAVACMD=$JAVA_HOME/bin/java
    if [ ! -x "$JAVACMD" ]; then
        echo "error: JAVA_HOME is set to an invalid directory: $JAVA_HOME" >&2
        exit 1
    fi
else
    JAVACMD=java
    if ! command -v java >/dev/null 2>&1; then
        echo "error: JAVA_HOME is not set and no 'java' command was found in PATH" >&2
        exit 1
    fi
fi
set -f
exec "$JAVACMD" {args}$JAVA_OPTS ${opts} -cp "{}" {} "$@"
"#,
        classpath.join(":"),
        sh_quote(&program.main_class)
    )
}

/// `bin/<program>.bat`, with CRLF line endings.
fn windows_script(program: &Program, jvm_args: &[String], jars: &[String], bundled: bool) -> String {
    let classpath: Vec<String> = jars.iter().map(|j| format!("%APP_HOME%\\lib\\{}", j.replace('%', "%%"))).collect();
    let args: String = jvm_args.iter().map(|a| format!("{} ", bat_quote(a))).collect();
    let opts = opts_variable(&program.name);
    let mut lines =
        vec!["@echo off".to_owned(), "rem Generated by Kargo.".to_owned(), "setlocal".to_owned(), "set \"APP_HOME=%~dp0..\"".to_owned()];
    if bundled {
        lines.push("if exist \"%APP_HOME%\\runtime\\bin\\java.exe\" goto bundled".to_owned());
    }
    lines.extend([
        "if defined JAVA_HOME goto javaHome".to_owned(),
        "set \"JAVACMD=java.exe\"".to_owned(),
        "where java.exe >nul 2>nul".to_owned(),
        "if errorlevel 1 goto noJava".to_owned(),
        "goto run".to_owned(),
        ":javaHome".to_owned(),
        "set \"JAVACMD=%JAVA_HOME%\\bin\\java.exe\"".to_owned(),
        "if exist \"%JAVACMD%\" goto run".to_owned(),
        "echo error: JAVA_HOME is set to an invalid directory: %JAVA_HOME% 1>&2".to_owned(),
        "exit /b 1".to_owned(),
        ":noJava".to_owned(),
        "echo error: JAVA_HOME is not set and no 'java' command was found in PATH 1>&2".to_owned(),
        "exit /b 1".to_owned(),
    ]);
    if bundled {
        lines.extend([":bundled".to_owned(), "set \"JAVACMD=%APP_HOME%\\runtime\\bin\\java.exe\"".to_owned()]);
    }
    lines.extend([
        ":run".to_owned(),
        format!("\"%JAVACMD%\" {args}%JAVA_OPTS% %{opts}% -cp \"{}\" {} %*", classpath.join(";"), bat_quote(&program.main_class)),
        "exit /b %ERRORLEVEL%".to_owned(),
    ]);
    lines.iter().map(|l| format!("{l}\r\n")).collect()
}

/// Whether a root file of the project goes into every distribution: README, LICENSE, NOTICE or COPYING.
fn is_notice_file(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    ["readme", "license", "licence", "notice", "copying"].iter().any(|p| name.starts_with(p))
}

/// Copies `include` paths, and the notice files of the project root, into `root`.
fn copy_extras(project: &Path, include: &[PathBuf], root: &Path) -> Result<()> {
    let mut paths: Vec<PathBuf> = Vec::new();
    if let Ok(entries) = std::fs::read_dir(project) {
        let mut found: Vec<PathBuf> = entries
            .filter_map(|e| e.ok())
            .filter(|e| e.file_type().is_ok_and(|t| t.is_file()) && is_notice_file(&e.file_name().to_string_lossy()))
            .map(|e| PathBuf::from(e.file_name()))
            .collect();
        found.sort();
        paths.extend(found);
    }
    for path in include {
        if !paths.contains(path) {
            paths.push(path.clone());
        }
    }
    for rel in paths {
        let from = project.join(&rel);
        if !from.exists() {
            bail!("[package.dist] `include` lists `{}`, which does not exist in the project", rel.display());
        }
        let to = root.join(&rel);
        if from.is_dir() {
            for entry in walkdir::WalkDir::new(&from).sort_by_file_name() {
                let entry = entry.with_context(|| format!("failed to read {}", from.display()))?;
                let rel_entry = entry.path().strip_prefix(&from).expect("walkdir yields paths under its root");
                let dest = to.join(rel_entry);
                if entry.file_type().is_dir() {
                    std::fs::create_dir_all(&dest)?;
                } else {
                    copy_file(entry.path(), &dest, root)?;
                }
            }
        } else {
            copy_file(&from, &to, root)?;
        }
    }
    Ok(())
}

fn copy_file(from: &Path, to: &Path, root: &Path) -> Result<()> {
    if to.exists() {
        bail!(
            "[package.dist] `include` would overwrite `{}`, which Kargo already put in the distribution",
            to.strip_prefix(root).unwrap_or(to).display()
        );
    }
    if let Some(parent) = to.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::copy(from, to).with_context(|| format!("failed to copy {}", from.display()))?;
    Ok(())
}

/// The mode of an archive entry, the same on every host: the start scripts and the runtime's
/// launchers (`runtime/bin/*` and the helpers of `runtime/lib`) are executable.
fn entry_mode(rel: &str, dir: bool) -> u32 {
    let script = rel.starts_with("bin/") && !rel.ends_with(".bat");
    let runtime = rel.starts_with("runtime/bin/") || ["runtime/lib/jspawnhelper", "runtime/lib/jexec"].contains(&rel);
    if dir || script || runtime { 0o755 } else { 0o644 }
}

/// Every entry of `root` as `(path relative to root with '/', is directory)`, sorted by path.
fn entries(root: &Path) -> Result<Vec<(String, bool)>> {
    let mut found = Vec::new();
    for entry in walkdir::WalkDir::new(root).min_depth(1) {
        let entry = entry.with_context(|| format!("failed to read {}", root.display()))?;
        let rel = entry.path().strip_prefix(root).expect("walkdir yields paths under its root");
        found.push((rel.to_string_lossy().replace('\\', "/"), entry.file_type().is_dir()));
    }
    found.sort();
    Ok(found)
}

/// Writes `root` as `dest`, with `top` as the single top-level directory.
fn archive(root: &Path, top: &str, kind: Archive, dest: &Path) -> Result<()> {
    let entries = entries(root)?;
    kargo_util::fs::write_atomic(dest, |file| match kind {
        Archive::Zip => write_zip(file, root, top, &entries),
        Archive::Tar => write_tar(file, root, top, &entries).map(drop),
        Archive::TarGz => {
            let encoder = flate2::GzBuilder::new().write(file, flate2::Compression::default());
            write_tar(encoder, root, top, &entries)?.finish().map(drop)
        }
    })
}

fn write_zip(file: &mut File, root: &Path, top: &str, entries: &[(String, bool)]) -> std::io::Result<()> {
    let to_io = std::io::Error::other;
    let options = |mode: u32| {
        zip::write::SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Deflated)
            .last_modified_time(zip::DateTime::default())
            // Unix on every host (zip records DOS on Windows, which drops the executable bit).
            .system(zip::System::Unix)
            .unix_permissions(mode)
    };
    let mut zip = zip::ZipWriter::new(file);
    zip.add_directory(format!("{top}/"), options(0o755)).map_err(to_io)?;
    for (rel, dir) in entries {
        let name = format!("{top}/{rel}");
        if *dir {
            zip.add_directory(format!("{name}/"), options(0o755)).map_err(to_io)?;
        } else {
            zip.start_file(name, options(entry_mode(rel, false))).map_err(to_io)?;
            std::io::copy(&mut File::open(root.join(rel))?, &mut zip)?;
        }
    }
    zip.finish().map_err(to_io)?;
    Ok(())
}

/// The tar timestamp: 1980-01-01, the same fixed time as the zip entries and the jars.
const TAR_MTIME: u64 = 315_532_800;

fn write_tar<W: Write>(out: W, root: &Path, top: &str, entries: &[(String, bool)]) -> std::io::Result<W> {
    let mut tar = tar::Builder::new(out);
    let header = |dir: bool, mode: u32, size: u64| {
        let mut h = tar::Header::new_gnu();
        h.set_entry_type(if dir { tar::EntryType::Directory } else { tar::EntryType::Regular });
        h.set_mode(mode);
        h.set_size(size);
        h.set_mtime(TAR_MTIME);
        h.set_uid(0);
        h.set_gid(0);
        h
    };
    tar.append_data(&mut header(true, 0o755, 0), format!("{top}/"), std::io::empty())?;
    for (rel, dir) in entries {
        let name = format!("{top}/{rel}");
        if *dir {
            tar.append_data(&mut header(true, 0o755, 0), format!("{name}/"), std::io::empty())?;
        } else {
            let path = root.join(rel);
            let size = std::fs::metadata(&path)?.len();
            tar.append_data(&mut header(false, entry_mode(rel, false), size), name, File::open(path)?)?;
        }
    }
    tar.into_inner()
}

/// `--dist`: stages the distribution and writes one archive per `archives`. `programs` get a start
/// script each (none with `scripts` off). With a `jlink` runtime, the distribution carries it in
/// `runtime/`, and each platform of `--platform` gets its own distribution and archives. Returns the archives.
pub fn dist(
    ctx: &BuildContext,
    jvm: &JvmBuild,
    programs: &[Program],
    archives: &[Archive],
    scripts: bool,
    runtime: Runtime,
) -> Result<Vec<PathBuf>> {
    let pkg = &ctx.ws.manifest().package;
    let out = ctx.ws.target_dir().join("dist");
    let main_class = programs.first().map(|p| p.main_class.clone()).unwrap_or_default();
    let app = App { name: &pkg.name, main_class, jvm, dir: out.clone() };
    let modules = match runtime {
        Runtime::System => None,
        Runtime::Jlink(_) => Some(runtime_modules(ctx, &app)?),
    };
    let platforms: Vec<Option<TargetPlatform>> = match runtime {
        Runtime::Jlink(platforms) if !platforms.is_empty() => platforms.iter().copied().map(Some).collect(),
        _ => vec![None],
    };
    let bundled = modules.is_some();
    let mut files = Vec::new();
    for platform in platforms {
        let top = match platform {
            Some(platform) => format!("{}-{}-{platform}", pkg.name, pkg.version),
            None => format!("{}-{}", pkg.name, pkg.version),
        };
        let root = out.join(&top);
        let what = platform.map(|p| format!(" for {p}")).unwrap_or_default();
        ctx.shell().status("Packaging", format!("{} v{} distribution{what} ({})", pkg.name, pkg.version, root.display()));
        remove_dir_all_if_exists(&root)?;
        let jars = app.stage_jars(ctx, &root.join("lib"), |_| false)?;
        if scripts {
            let bin = root.join("bin");
            std::fs::create_dir_all(&bin)?;
            for program in programs {
                let app = App { name: &program.name, main_class: program.main_class.clone(), jvm, dir: out.clone() };
                let jvm_args = app_jvm_args(ctx, &app, None)?;
                let script = bin.join(&program.name);
                kargo_util::fs::write_string_atomic(&script, &unix_script(program, &jvm_args, &jars, bundled))?;
                #[cfg(unix)]
                {
                    use std::os::unix::fs::PermissionsExt;
                    std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755))?;
                }
                kargo_util::fs::write_string_atomic(
                    &bin.join(format!("{}.bat", program.name)),
                    &windows_script(program, &jvm_args, &jars, bundled),
                )?;
            }
        }
        if let Some(modules) = &modules {
            jlink(ctx, modules, &root.join("runtime"), platform)?;
        }
        copy_extras(ctx.ws.root(), &ctx.ws.manifest().packaging.dist.include, &root)?;
        for kind in archives {
            let dest = out.join(format!("{top}.{}", kind.extension()));
            archive(&root, &top, *kind, &dest)?;
            files.push(dest);
        }
    }
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn program(name: &str) -> Program {
        Program { name: name.to_owned(), main_class: "com.example.MainKt".to_owned() }
    }

    #[test]
    fn options_variables() {
        assert_eq!(opts_variable("my-app"), "MY_APP_OPTS");
        assert_eq!(opts_variable("3d.viewer"), "_3D_VIEWER_OPTS");
    }

    #[test]
    fn unix_script_content() {
        let script = unix_script(
            &program("my-app"),
            &["-Xmx512m".to_owned(), "-Dname=a b".to_owned()],
            &["app-1.0.jar".into(), "dep.jar".into()],
            false,
        );
        assert!(script.starts_with("#!/bin/sh\n"));
        assert!(script.contains("JAVA_HOME"), "{script}");
        assert!(script.contains("command -v java"), "{script}");
        assert!(
            script.contains(
                "exec \"$JAVACMD\" -Xmx512m '-Dname=a b' $JAVA_OPTS $MY_APP_OPTS -cp \"$APP_HOME/lib/app-1.0.jar:$APP_HOME/lib/dep.jar\" com.example.MainKt \"$@\""
            ),
            "{script}"
        );
        assert!(!script.contains('\r'));
        assert!(!script.contains("runtime"), "{script}");
    }

    #[test]
    fn unix_script_prefers_the_bundled_runtime() {
        let script = unix_script(&program("my-app"), &[], &["app-1.0.jar".into()], true);
        let runtime = script.find("[ -x \"$APP_HOME/runtime/bin/java\" ]").expect("checks the runtime");
        assert!(script.contains("JAVACMD=$APP_HOME/runtime/bin/java\nelif [ -n \"$JAVA_HOME\" ]; then"), "{script}");
        assert!(runtime < script.find("JAVA_HOME").unwrap(), "the runtime comes before JAVA_HOME and PATH: {script}");
        assert!(script.contains("exec \"$JAVACMD\" $JAVA_OPTS"), "{script}");
    }

    #[test]
    fn windows_script_content() {
        let script = windows_script(&program("my-app"), &["-Dname=a b".to_owned()], &["app-1.0.jar".into(), "dep.jar".into()], false);
        assert!(script.contains("%JAVA_HOME%\\bin\\java.exe"), "{script}");
        assert!(
            script.contains(
                "\"%JAVACMD%\" \"-Dname=a b\" %JAVA_OPTS% %MY_APP_OPTS% -cp \"%APP_HOME%\\lib\\app-1.0.jar;%APP_HOME%\\lib\\dep.jar\" com.example.MainKt %*"
            ),
            "{script}"
        );
        assert!(script.lines().all(|l| !l.is_empty()) && script.ends_with("\r\n"));
        assert!(!script.contains("runtime"), "{script}");
    }

    #[test]
    fn windows_script_prefers_the_bundled_runtime() {
        let script = windows_script(&program("my-app"), &[], &["app-1.0.jar".into()], true);
        let lines: Vec<&str> = script.lines().collect();
        let position = |text: &str| lines.iter().position(|l| *l == text).unwrap_or_else(|| panic!("no `{text}` in {script}"));
        let check = position("if exist \"%APP_HOME%\\runtime\\bin\\java.exe\" goto bundled");
        assert!(check < position("if defined JAVA_HOME goto javaHome"), "{script}");
        assert_eq!(lines[position(":bundled") + 1], "set \"JAVACMD=%APP_HOME%\\runtime\\bin\\java.exe\"");
        assert_eq!(position(":bundled") + 2, position(":run"), "{script}");
    }

    #[test]
    fn modes() {
        assert_eq!(entry_mode("bin/app", false), 0o755);
        assert_eq!(entry_mode("bin/app.bat", false), 0o644);
        assert_eq!(entry_mode("lib/app.jar", false), 0o644);
        assert_eq!(entry_mode("conf", true), 0o755);
        assert_eq!(entry_mode("runtime/bin/java", false), 0o755);
        assert_eq!(entry_mode("runtime/bin/java.exe", false), 0o755);
        assert_eq!(entry_mode("runtime/lib/jspawnhelper", false), 0o755);
        assert_eq!(entry_mode("runtime/lib/modules", false), 0o644);
        assert_eq!(entry_mode("runtime/release", false), 0o644);
        assert!(is_notice_file("LICENSE-APACHE") && is_notice_file("README.md") && !is_notice_file("build.gradle"));
    }

    #[test]
    fn archives_are_reproducible_and_sorted() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("app-1.0");
        std::fs::create_dir_all(root.join("bin")).unwrap();
        std::fs::create_dir_all(root.join("lib")).unwrap();
        std::fs::create_dir_all(root.join("runtime/bin")).unwrap();
        std::fs::create_dir_all(root.join("runtime/lib")).unwrap();
        std::fs::write(root.join("runtime/bin/java"), "elf").unwrap();
        std::fs::write(root.join("runtime/lib/modules"), "jimage").unwrap();
        std::fs::write(root.join("bin/app"), "#!/bin/sh\n").unwrap();
        std::fs::write(root.join("lib/app-1.0.jar"), "jar").unwrap();
        std::fs::write(root.join("README.md"), "hi").unwrap();
        for (kind, name) in [(Archive::Zip, "a.zip"), (Archive::Tar, "a.tar"), (Archive::TarGz, "a.tar.gz")] {
            let (first, second) = (dir.path().join(name), dir.path().join(format!("b-{name}")));
            archive(&root, "app-1.0", kind, &first).unwrap();
            archive(&root, "app-1.0", kind, &second).unwrap();
            assert_eq!(std::fs::read(&first).unwrap(), std::fs::read(&second).unwrap(), "{name}");
        }
        let mut tar = tar::Archive::new(File::open(dir.path().join("a.tar")).unwrap());
        let names: Vec<String> = tar
            .entries()
            .unwrap()
            .map(|e| {
                let e = e.unwrap();
                format!("{}:{:o}", e.path().unwrap().display(), e.header().mode().unwrap())
            })
            .collect();
        assert_eq!(
            names,
            [
                "app-1.0/:755",
                "app-1.0/README.md:644",
                "app-1.0/bin/:755",
                "app-1.0/bin/app:755",
                "app-1.0/lib/:755",
                "app-1.0/lib/app-1.0.jar:644",
                "app-1.0/runtime/:755",
                "app-1.0/runtime/bin/:755",
                "app-1.0/runtime/bin/java:755",
                "app-1.0/runtime/lib/:755",
                "app-1.0/runtime/lib/modules:644"
            ]
        );
        let mut zip = zip::ZipArchive::new(File::open(dir.path().join("a.zip")).unwrap()).unwrap();
        assert_eq!(zip.by_name("app-1.0/bin/app").unwrap().unix_mode(), Some(0o100755));
        assert_eq!(zip.by_name("app-1.0/runtime/bin/java").unwrap().unix_mode(), Some(0o100755));
    }
}
