//! Kotlin/Wasm declarations for npm packages, generated from their TypeScript declarations
//! (their own `.d.ts` files, or those of `@types/<name>`), so Kotlin code calls an npm package
//! like a Kotlin library: `express()` instead of hand-written `@JsModule` wrappers. The project's
//! own TypeScript modules get them the same way ([`generate_local`]).
//!
//! The files are read as TypeScript would ([`program`]), parsed into declarations
//! ([`parser`]), and turned into `external` declarations ([`kotlin`]): one Kotlin package per npm
//! package, named after it (`express`, `@acme/my-lib` is `acme.my_lib`), or one per subpath of a
//! package whose `exports` map has no root (`cubing/alg` is `cubing.alg`). Only signatures are read,
//! so a `.ts` file's function bodies are skipped and nothing is inferred from them.

mod kotlin;
mod lexer;
mod parser;
mod program;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use parser::DeclKind;
use program::Ent;

pub use kotlin::{FACTORIES_DIR, function_name, kotlin_package};
pub use program::types_name;

/// Bumped whenever the generated Kotlin changes, so that declarations generated before are written again.
pub const FORMAT: u32 = 6;

/// What [`generate`] wrote.
#[derive(Debug, Default)]
pub struct Generated {
    /// The Kotlin files (the factory modules next to them are not listed).
    pub files: Vec<PathBuf>,
    /// The packages without TypeScript declarations, which got none.
    pub untyped: Vec<String>,
}

/// Whether the npm package installed in `node_modules` has TypeScript declarations, of its own
/// or from `@types`.
pub fn has_declarations(node_modules: &Path, package: &str) -> bool {
    program::resolve_bare(node_modules, package).is_some() || !program::subpaths(node_modules, package).is_empty()
}

/// Writes Kotlin declarations for the npm `packages` into `out` (replacing what is there),
/// reading TypeScript declarations from the `node_modules` folders `roots`. `@types/` packages
/// describe the package they are named after and get no declarations of their own.
pub fn generate(packages: &[String], roots: &[PathBuf], out: &Path) -> Result<Generated> {
    let mut prog = program::Program::new(roots.to_vec());
    let mut generated = Generated::default();
    let mut found = Vec::new();
    for npm in packages.iter().filter(|p| !p.starts_with("@types/")) {
        let modules = prog.package_modules(npm);
        if modules.is_empty() {
            generated.untyped.push(npm.clone());
        }
        found.extend(modules);
    }
    let mut generator = kotlin::Generator::new(&mut prog);
    // Every module's classes first, so that one subpath's references to a class of another use the class.
    for (spec, module) in &found {
        generator.classes(&kotlin_package(spec), spec, *module);
    }
    for (spec, module) in found {
        generator.package(&spec, module);
    }
    let output = generator.finish();

    kargo_util::fs::remove_dir_all_if_exists(out)?;
    let header = |content: &kotlin::KotlinPackage| {
        format!(
            "// Generated by Kargo from the TypeScript declarations of the npm package `{}`.\n// Do not edit: Kargo writes it again when the package changes.\n",
            content.npm
        )
    };
    for (path, text) in render(&output, out, header) {
        std::fs::create_dir_all(path.parent().expect("a generated file is in a package directory"))?;
        std::fs::write(&path, text).with_context(|| format!("failed to write {}", path.display()))?;
        if is_kotlin(&path) {
            generated.files.push(path);
        }
    }
    Ok(generated)
}

fn is_kotlin(path: &Path) -> bool {
    path.extension().is_some_and(|e| e == "kt")
}

/// The JavaScript modules with the factories that [`generate`] and [`generate_local`] write below
/// `out`, by their path below the project's JavaScript modules (`kargo-factories/express.mjs`).
pub fn factory_modules(out: &Path) -> Vec<(String, PathBuf)> {
    let dir = out.join(FACTORIES_DIR);
    let mut modules: Vec<(String, PathBuf)> = kargo_util::fs::collect_files(&dir, &["mjs"])
        .into_iter()
        .filter_map(|p| Some((format!("{FACTORIES_DIR}/{}", p.file_name()?.to_str()?), p)))
        .collect();
    modules.sort();
    modules
}

/// The files of `output` below `out`, each starting with `header`: `Types.kt`, `Exports.kt`
/// (under `@file:JsModule`), `Default.kt` and `Factories.kt` (under `@file:JsModule` of the
/// factory module) in the directory of each Kotlin package, and the factory module itself in
/// [`FACTORIES_DIR`].
fn render(output: &kotlin::Output, out: &Path, header: impl Fn(&kotlin::KotlinPackage) -> String) -> Vec<(PathBuf, String)> {
    let mut files = Vec::new();
    for (package, content) in &output.packages {
        let dir = package.split('.').fold(out.to_path_buf(), |dir, part| dir.join(part));
        let factories = kotlin::factory_module(package);
        let parts = [
            ("Types.kt", None, &content.types),
            ("Exports.kt", Some(&content.npm), &content.exports),
            ("Default.kt", None, &content.default),
            ("Factories.kt", Some(&factories), &content.factories),
        ];
        for (name, module, decls) in parts {
            if decls.is_empty() {
                continue;
            }
            let mut text = header(content);
            if let Some(module) = module {
                text.push_str(&format!("@file:JsModule(\"{module}\")\n"));
            }
            text.push_str(&format!("\npackage {package}\n\nimport kotlin.js.*\n"));
            for decl in decls.iter() {
                text.push('\n');
                text.push_str(decl);
                text.push('\n');
            }
            files.push((dir.join(name), text));
        }
        if !content.factory_js.is_empty() {
            let mut text = header(content);
            let _ = writeln!(
                text,
                "// The factories of the Kotlin package `{package}`: each builds an object from its properties, leaving out those that are `undefined`."
            );
            for function in &content.factory_js {
                text.push('\n');
                text.push_str(function);
                text.push('\n');
            }
            files.push((out.join(FACTORIES_DIR).join(format!("{package}.mjs")), text));
        }
    }
    files
}

/// One of the project's own JavaScript modules with TypeScript types: a `.ts` or `.mts` file, or
/// the `.d.ts` / `.d.mts` file written next to a `.js` / `.mjs` one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LocalModule {
    /// The TypeScript file.
    pub file: PathBuf,
    /// The file as messages and the generated header name it, relative to the package (`js/canvas.ts`).
    pub display: String,
    /// The Kotlin package of its declarations (`js.canvas`).
    pub package: String,
    /// The module Kotlin imports at runtime, relative to the Kotlin module (`./js/canvas.js`).
    pub spec: String,
}

/// What [`generate_local`] wrote.
#[derive(Debug, Default)]
pub struct LocalGenerated {
    /// Every Kotlin file of the declarations (the factory modules next to them are not listed).
    pub files: Vec<PathBuf>,
    /// The files whose text changed (new ones included), and those it removed.
    pub changed: Vec<PathBuf>,
    /// Exported functions with a parameter or return type left to inference, which Kotlin sees as
    /// `JsAny?`: the module's `display` and the function's name.
    pub untyped: Vec<(String, String)>,
}

/// Writes Kotlin declarations for the project's own `modules` into `out`, reading the npm packages
/// they import from the `node_modules` folders `roots`. Types from npm packages are `JsAny`: the
/// packages get declarations of their own ([`generate`]). Only the files whose text changed are
/// written, and files of modules that are gone are removed, so that the compilers and an editor
/// see the rest unchanged.
pub fn generate_local(modules: &[LocalModule], roots: &[PathBuf], out: &Path) -> Result<LocalGenerated> {
    let mut prog = program::Program::new(roots.to_vec());
    let mut generated = LocalGenerated::default();
    let scopes: Vec<_> = modules.iter().map(|m| prog.load(&m.file)).collect();
    for (module, scope) in modules.iter().zip(&scopes) {
        let Some(scope) = *scope else { continue };
        for name in prog.export_names(scope) {
            let Some(Ent::Decls(decls)) = prog.export(scope, &name) else { continue };
            if decls.iter().any(|&d| matches!(&prog.decls[d].decl.kind, DeclKind::Function(sig) if sig.untyped)) {
                generated.untyped.push((module.display.clone(), name));
            }
        }
    }
    let mut generator = kotlin::Generator::new(&mut prog);
    for module in modules {
        generator.local(&module.file, &module.package, &module.spec);
    }
    for (module, scope) in modules.iter().zip(scopes) {
        let Some(scope) = scope else { continue };
        let stem = module.spec.rsplit('/').next().unwrap_or(&module.spec);
        let stem = stem.split('.').next().unwrap_or(stem);
        generator.module(&module.package, &module.spec, &function_name(stem), scope);
    }
    let output = generator.finish();

    let sources: BTreeMap<&str, &str> = modules.iter().map(|m| (m.spec.as_str(), m.display.as_str())).collect();
    let header = |content: &kotlin::KotlinPackage| {
        let source = sources.get(content.npm.as_str()).copied().unwrap_or(content.npm.as_str());
        format!(
            "// Generated by Kargo from the TypeScript declarations of `{source}`.\n// Do not edit: Kargo writes it again when the file changes.\n"
        )
    };
    let files = render(&output, out, header);
    let wanted: std::collections::HashSet<&Path> = files.iter().map(|(p, _)| p.as_path()).collect();
    for stale in kargo_util::fs::collect_files(out, &["kt", "mjs"]).into_iter().filter(|p| !wanted.contains(p.as_path())) {
        std::fs::remove_file(&stale).with_context(|| format!("failed to remove {}", stale.display()))?;
        generated.changed.push(stale);
    }
    for (path, text) in files {
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            std::fs::create_dir_all(path.parent().expect("a generated file is in a package directory"))?;
            std::fs::write(&path, &text).with_context(|| format!("failed to write {}", path.display()))?;
            generated.changed.push(path.clone());
        }
        if is_kotlin(&path) {
            generated.files.push(path);
        }
    }
    Ok(generated)
}

